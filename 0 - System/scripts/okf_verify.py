#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
okf_verify.py — mark that you have read a page and confirmed it is correct.

    generated_by  = who produced this (an agent, a pipeline, you)
    verified      = who *reviewed* it and signed off

Without `verified` a page is unverified, even if it is perfectly accurate. Stamping is
deliberate: this script is the only thing that writes the key.

Usage:
    python3 "0 - System/scripts/okf_verify.py" "7 - Wikipedia/Stop Loss.md"
    python3 "0 - System/scripts/okf_verify.py" --pending     # what is waiting for sign-off
    python3 "0 - System/scripts/okf_verify.py" --list        # what is already verified

Set OKF_ACTOR to your own identity (default: human:me).
"""
import os, sys, argparse
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import okf

ACTOR = os.environ.get("OKF_ACTOR", "human:me")


def is_verified(meta):
    return isinstance(meta.get("verified"), list) and bool(meta["verified"])


def in_content(p):
    p = Path(os.path.abspath(p))
    return any(folder in p.parents for folder in okf.CONTENT) and not okf.has_symlink(p)


def stamp(paths):
    touched = []
    for raw in paths:
        p = Path(raw) if Path(raw).is_absolute() else okf.VAULT / raw
        if not in_content(p) or not p.is_file():
            print(f"  ⚠️  not a page in the content folders: {raw}")
            continue
        meta, body = okf.read_page(p)
        if not meta:
            print(f"  ⚠️  no readable frontmatter: {okf.rel(p)}")
            continue
        ver = meta.get("verified") if isinstance(meta.get("verified"), list) else []
        if any(isinstance(e, dict) and e.get("by") == ACTOR for e in ver):
            print(f"  ↻  already verified: {okf.rel(p)}")
            continue
        meta["verified"] = ver + [{"by": ACTOR, "at": okf.today()}]
        touched.append((p, meta, body))

    if not touched:
        return
    okf.backup([p for p, _, _ in touched], "verify")
    for p, meta, body in touched:
        p.write_text(okf.render_page(meta, body), encoding="utf-8")
        print(f"  ✅ {okf.rel(p)}")
    print(f"\n{len(touched)} pages marked verified by {ACTOR}.")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("paths", nargs="*", help="files to stamp")
    ap.add_argument("--list", action="store_true", help="what is already verified")
    ap.add_argument("--pending", action="store_true", help="what is waiting for sign-off")
    args = ap.parse_args()

    if args.list or args.pending:
        rows = [(p, meta) for _, p, meta, _ in okf.iter_pages() if is_verified(meta) == args.list]
        print(f"{'Verified' if args.list else 'Awaiting sign-off'}: {len(rows)}\n")
        for p, meta in rows:
            if args.list:
                who = ", ".join(f"{e.get('by')}@{e.get('at')}"
                                for e in meta["verified"] if isinstance(e, dict))
                print(f"  ✅ {okf.rel(p)}  ({who})")
            else:
                by = str(meta.get("generated_by", "") or "").strip() or "?"
                print(f"  ⬜ {okf.rel(p)}  (generated by {by})")
    elif args.paths:
        stamp(args.paths)
    else:
        ap.print_help()


if __name__ == "__main__":
    main()
